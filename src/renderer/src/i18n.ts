/** 设置语言 → i18n 实际语言（system 按系统区域） */
export function resolveLanguage(setting: 'system' | 'zh-CN' | 'en-US'): 'zh-CN' | 'en-US' {
  if (setting !== 'system') return setting
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

i18n.use(initReactI18next).init({
  resources,
  lng: resolveLanguage(getSettingsSnapshot().language),
  fallbackLng: 'zh-CN',
  interpolation: { escapeValue: false }
})

// 启动时以持久化设置为准（getSettingsSnapshot 在模块加载时还是默认值 system）
window.api.settings.get().then((s) => {
  const next = resolveLanguage(s.language)
  if (i18n.language !== next) i18n.changeLanguage(next)
})

// 设置变更即时切换语言
window.api.settings.onChanged((s) => {
  const next = resolveLanguage(s.language)
  if (i18n.language !== next) i18n.changeLanguage(next)
})

export default i18n
